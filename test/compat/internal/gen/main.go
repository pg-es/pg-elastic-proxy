// Command gen reads an Elasticsearch REST API specification and writes a
// name-to-route registry used by the compat executor. Run it once per ES major:
//
//	go run ./test/compat/internal/gen \
//	    -spec /path/to/elasticsearch-8.19/rest-api-spec/src/main/resources/rest-api-spec/api \
//	    -name actionRoutesES8 -out test/compat/action_registry_es8.go
//
// Prefer `mise run compat:gen`, which regenerates both registries.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const (
	exitUsage = 2
	filePerm  = 0o600
)

type specPath struct {
	Path    string         `json:"path"`
	Methods []string       `json:"methods"`
	Parts   map[string]any `json:"parts"`
}

type specAction struct {
	URL struct {
		Paths []specPath `json:"paths"`
	} `json:"url"`
	Params map[string]any `json:"params"`
}

type specFile map[string]specAction

type actionPath struct {
	Template string
	Methods  []string
	Parts    []string
}

type actionRoute struct {
	Paths       []actionPath
	QueryParams []string
}

func main() {
	specDir := flag.String("spec", "", "directory of Elasticsearch REST API spec JSON files")
	outFile := flag.String("out", "", "path of the Go file to write")
	varName := flag.String("name", "actionRoutes", "name of the generated map variable")

	flag.Parse()

	if *specDir == "" || *outFile == "" {
		fmt.Fprintln(os.Stderr, "both -spec and -out are required")
		os.Exit(exitUsage)
	}

	routes, err := loadRoutes(*specDir)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	err = os.WriteFile(*outFile, []byte(render(routes, *varName)), filePerm)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	fmt.Printf("wrote %d actions to %s\n", len(routes), *outFile)
}

func loadRoutes(specDir string) (map[string]actionRoute, error) {
	files, err := filepath.Glob(filepath.Join(specDir, "*.json"))
	if err != nil {
		return nil, fmt.Errorf("glob spec files: %w", err)
	}

	routes := make(map[string]actionRoute)

	for _, file := range files {
		if strings.HasPrefix(filepath.Base(file), "_") {
			continue
		}

		//nolint:gosec // the spec path is supplied by the developer running the generator
		raw, readErr := os.ReadFile(file)
		if readErr != nil {
			return nil, fmt.Errorf("read spec file: %w", readErr)
		}

		var parsed specFile

		unmarshalErr := json.Unmarshal(raw, &parsed)
		if unmarshalErr != nil {
			return nil, fmt.Errorf("%s: %w", file, unmarshalErr)
		}

		for name, spec := range parsed {
			if strings.HasPrefix(name, "_") || len(spec.URL.Paths) == 0 {
				continue
			}

			routes[name] = buildRoute(spec)
		}
	}

	return routes, nil
}

func buildRoute(spec specAction) actionRoute {
	route := actionRoute{QueryParams: sortedKeys(spec.Params)}

	for _, path := range spec.URL.Paths {
		route.Paths = append(route.Paths, actionPath{
			Template: path.Path,
			Methods:  path.Methods,
			Parts:    sortedKeys(path.Parts),
		})
	}

	return route
}

func sortedKeys(m map[string]any) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}

	sort.Strings(keys)

	return keys
}

func render(routes map[string]actionRoute, varName string) string {
	names := make([]string, 0, len(routes))
	for actionName := range routes {
		names = append(names, actionName)
	}

	sort.Strings(names)

	var builder strings.Builder

	builder.WriteString("// Code generated by test/compat/internal/gen; DO NOT EDIT.\n")
	builder.WriteString("// Source: elastic/elasticsearch rest-api-spec/api.\n\n")
	builder.WriteString("package compat\n\n")
	fmt.Fprintf(&builder, "// %s maps ES client-test action names to their REST routes.\n", varName)
	fmt.Fprintf(&builder, "var %s = map[string]ActionRoute{\n", varName)

	for _, actionName := range names {
		route := routes[actionName]
		fmt.Fprintf(&builder, "\t%q: {\n", actionName)

		builder.WriteString("\t\tPaths: []ActionPath{\n")

		for _, path := range route.Paths {
			fmt.Fprintf(&builder, "\t\t\t{Template: %q, Methods: %s, Parts: %s},\n",
				path.Template, stringSlice(path.Methods), stringSlice(path.Parts))
		}

		builder.WriteString("\t\t},\n")

		if len(route.QueryParams) > 0 {
			fmt.Fprintf(&builder, "\t\tQueryParams: %s,\n", stringSlice(route.QueryParams))
		}

		builder.WriteString("\t},\n")
	}

	builder.WriteString("}\n")

	return builder.String()
}

func stringSlice(values []string) string {
	quoted := make([]string, len(values))
	for i, v := range values {
		quoted[i] = fmt.Sprintf("%q", v)
	}

	return "[]string{" + strings.Join(quoted, ", ") + "}"
}
